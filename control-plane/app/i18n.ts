export const supportedLocales = ['en', 'ru'] as const;
export type Locale = (typeof supportedLocales)[number];

export const localeCookieName = '2papi_locale';
export const localeStorageKey = '2papi.locale';

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && supportedLocales.includes(value as Locale);
}

export function localeFromAcceptLanguage(header: string | null | undefined): Locale {
  if (!header) return 'en';

  const ranges = header
    .split(',')
    .map((part, index) => {
      const [tag = '', ...parameters] = part.trim().toLowerCase().split(';');
      const qualityParameter = parameters.find(parameter => parameter.trim().startsWith('q='));
      const quality = qualityParameter ? Number.parseFloat(qualityParameter.trim().slice(2)) : 1;
      return { tag, quality: Number.isFinite(quality) ? quality : 0, index };
    })
    .sort((left, right) => right.quality - left.quality || left.index - right.index);

  for (const { tag, quality } of ranges) {
    if (quality <= 0) continue;
    const language = tag.split('-')[0];
    if (language === 'ru') return 'ru';
    if (language === 'en') return 'en';
  }

  return 'en';
}

export function resolveLocale(stored: string | null | undefined, acceptLanguage?: string | null): Locale {
  return isLocale(stored) ? stored : localeFromAcceptLanguage(acceptLanguage);
}

